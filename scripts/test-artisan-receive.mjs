import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const load = async source => import('data:text/javascript;base64,' + Buffer.from(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText).toString('base64'));
const read = p => readFile(new URL('../' + p, import.meta.url), 'utf8');
const prod = await load(await read('lib/production.ts'));
globalThis.receiveProduction = prod;
const { artisanPending, artisanReceiptCommand } = await load((await read('lib/artisan-receive.ts')).replace(/import \{[^;]+\} from '\.\/production';/, 'const {accountKey}=globalThis.receiveProduction;'));
const { planCommand, accountKey } = prod;
const a = (company, product, artisan, stage = 'artist', pool = 'normal', work = 'R') => ({ company, product, artisan, stage, pool, work, arts: '' });
const silk = a('A', 'silk', 'X'), tussar = a('A', 'tussar', 'X'), other = a('B', 'silk', 'X'), returned = a('A', 'silk', 'X', 'artist', 'company_return'), empty = a('C', 'silk', 'X');
let balances = [{ ...silk, quantity: 50 }, { ...tussar, quantity: 10 }, { ...other, quantity: 12 }, { ...returned, quantity: 5 }, { ...empty, quantity: 0 }, { ...a('A','silk','Y'), quantity: 100 }];
const date = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
const draft = { artisan: 'X', company: 'A', date, quantities: { [accountKey(silk)]: 20, [accountKey(tussar)]: 5 }, disputed: true, disputes: { [accountKey(silk)]: 3 }, notes: '' };
assert.equal(artisanPending(balances, 'X').length, 4);
assert.equal(artisanPending(balances, '').length, 0);
const command = artisanReceiptCommand(draft, balances);
assert.equal(command.lines.length, 2);
const post = c => { const p = planCommand(c, balances); for (const d of p.deltas) { const b = balances.find(b => accountKey(b) === accountKey(d)); if(b)b.quantity += d.quantity;else balances.push({...d}); } return p; };
const q = a => balances.find(b => accountKey(a) === accountKey(b))?.quantity || 0;
const before = balances.reduce((s,b)=>s+b.quantity,0);
assert.deepEqual(post(command).money, []);
assert.equal(q(silk), 30);assert.equal(q({...silk,stage:'reprint'}),3);
assert.equal(q({...silk,stage:'ready',artisan:'',work:'',arts:'R'}),17);
assert.equal(q(returned),5);assert.equal(q(other),12);
assert.equal(balances.reduce((s,b)=>s+b.quantity,0),before, 'Receipt + repaint conserves physical custody');
assert.equal(artisanPending(balances,'X').filter(b=>b.pool==='normal').reduce((s,b)=>s+b.quantity,0),50);
const repaint = { ...silk, stage: 'reprint' };
post({ kind:'receive', date, lines:[{source:repaint,quantity:3,disputeQuantity:1}] });
assert.equal(q(repaint),1);assert.equal(q({...silk,stage:'ready',artisan:'',work:'',arts:'R'}),19);
post({kind:'receive',date,lines:[{source:silk,quantity:4,disputeQuantity:4}]});assert.equal(q(repaint),5);assert.equal(q(silk),26);
for(const n of [-1,21,0.5,NaN])assert.throws(()=>planCommand({kind:'receive',date,lines:[{source:silk,quantity:20,disputeQuantity:n}]},balances));
assert.throws(()=>artisanReceiptCommand({...draft,artisan:'Z'},balances));
assert.throws(()=>artisanReceiptCommand({...draft,quantities:{[accountKey(returned)]:1}},balances));
assert.throws(()=>artisanReceiptCommand({...draft,quantities:{[accountKey(other)]:1}},balances));
assert.throws(()=>artisanReceiptCommand({...draft,quantities:{[accountKey(silk)]:99}},balances));
assert.throws(()=>artisanReceiptCommand({...draft,quantities:{}},balances));
assert.throws(()=>artisanReceiptCommand({...draft,quantities:{[accountKey(silk)]:2}},balances));
assert.throws(()=>planCommand({kind:'receive',date,lines:[{source:returned,quantity:1,disputeQuantity:0}]},balances));
assert.throws(()=>planCommand({kind:'return_receive',date,lines:[{source:returned,quantity:1,disputeQuantity:1}]},balances));
// Historical hold receipts keep their original meaning when corrected/replayed.
assert.equal(planCommand({kind:'receive',date,lines:[{source:silk,quantity:1,outcome:'hold'}]},balances).deltas[1].stage,'hold');
console.log('PASS: artisan/company/category isolation; partial and all-dispute receipts; repaint re-receipt; conservation; bounds; legacy receipt compatibility.');
